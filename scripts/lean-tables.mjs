#!/usr/bin/env node
// AWSの表を、Leanのデータ`ProofGate/Tables.lean`として書き出します（spec proofgate-lean-evaluator, design 5.2）。
// 元は、TypeScriptの評価器が使う表と同じファイルです（`packages/core/src/aws-tables.generated.ts`と
// `launch-supplements.ts`）。ネットワークは使いません。`scripts/sync-service-reference.mjs`の後にも実行します。
// Writes the AWS tables as Lean data, `ProofGate/Tables.lean`, from the same files that the TypeScript evaluator uses.
// No network. Run it after `scripts/sync-service-reference.mjs` too. `tests/lean-tables.test.ts` checks that the committed
// file equals this output.
//
// Usage: node scripts/lean-tables.mjs
import { writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";
import {
  BUCKET_GRANT_ACTIONS,
  LAUNCH_ACTIONS,
  OBJECT_ACTIONS,
} from "../packages/core/src/aws-tables.generated.ts";
import { LAUNCH_SUPPLEMENTS } from "../packages/core/src/launch-supplements.ts";

const leanString = (value) => JSON.stringify(value);
const list = (values, indent = "  ") =>
  values.length === 0 ? "[]" : `[\n${values.map((v) => `${indent}${v}`).join(",\n")}\n]`;

/** 起動アクションの表に補足を足し、サービス名の接頭辞（`:`より前）でまとめます。 Groups the launch table by service prefix. */
export function launchGroups() {
  const groups = new Map();
  for (const [action, base] of Object.entries(LAUNCH_ACTIONS)) {
    const services = [...new Set([...base, ...(LAUNCH_SUPPLEMENTS[action] ?? [])])];
    const at = action.indexOf(":");
    const prefix = action.slice(0, at);
    const name = action.slice(at + 1);
    if (!groups.has(prefix)) groups.set(prefix, []);
    groups.get(prefix).push([name, services]);
  }
  return [...groups.entries()];
}

/** Tables.leanの本文を返します。 Returns the text of Tables.lean. */
export function renderLeanTables() {
  const groups = launchGroups();
  const allServices = [
    ...new Set(groups.flatMap(([, entries]) => entries.flatMap(([, s]) => s))),
  ].sort();
  const objectActions = [...OBJECT_ACTIONS, "s3:*"];
  const entryCount = groups.reduce((n, [, entries]) => n + entries.length, 0);
  return [
    "/-!",
    "# ProofGate.Tables",
    "",
    "このファイルは`scripts/lean-tables.mjs`が生成します。手で編集しません。",
    "Generated by `scripts/lean-tables.mjs` from `packages/core/src/aws-tables.generated.ts` and",
    "`packages/core/src/launch-supplements.ts`, the same tables that the TypeScript evaluator uses. Do not edit by hand.",
    `Counts: ${OBJECT_ACTIONS.length} object actions and \`s3:*\`, ${BUCKET_GRANT_ACTIONS.length} bucket grant actions,`,
    `${entryCount} launch actions in ${groups.length} service groups, ${allServices.length} distinct service values.`,
    "-/",
    "",
    "namespace ProofGate.Tables",
    "",
    "/-- The S3 actions on the `object` resource (lowercase), and `s3:*`, which the evaluator keeps as one entry. -/",
    `def objectActions : List String := ${list(objectActions.map(leanString))}`,
    "",
    "/-- The bucket actions that change permissions, replication, or lifecycle (lowercase). -/",
    `def bucketGrantActions : List String := ${list(BUCKET_GRANT_ACTIONS.map(leanString))}`,
    "",
    '/-- The launch actions grouped by service prefix: (prefix, [(action name, services)]). `"*"` means any service. -/',
    `def launchGroups : List (String × List (String × List String)) := ${list(
      groups.map(
        ([prefix, entries]) =>
          `(${leanString(prefix)}, [${entries
            .map(
              ([name, services]) =>
                `(${leanString(name)}, [${services.map(leanString).join(", ")}])`,
            )
            .join(", ")}])`,
      ),
    )}`,
    "",
    '/-- Every service value of the launch table, including `"*"`, sorted. Used for an action pattern that starts with `*`. -/',
    `def allLaunchServices : List String := ${list(allServices.map(leanString))}`,
    "",
    "end ProofGate.Tables",
    "",
  ].join("\n");
}

const out = join(
  resolve(dirname(fileURLToPath(import.meta.url)), ".."),
  "packages/cdk-plugin/lean/ProofGate/Tables.lean",
);
if (process.argv[1] !== undefined && resolve(process.argv[1]) === fileURLToPath(import.meta.url)) {
  writeFileSync(out, renderLeanTables());
  console.log(`wrote ${out}`);
}
